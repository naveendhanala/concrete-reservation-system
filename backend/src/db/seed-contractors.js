async function seed() {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('UPDATE reservations SET contractor_id = NULL');
    await client.query('DELETE FROM contractors');
    console.log('Cleared existing contractors.');

    for (const name of CONTRACTORS) {
      await client.query(
        `INSERT INTO contractors (name) VALUES ($1)`,
        [name.trim()]
      );
    }

    await client.query('COMMIT');
    console.log(`✅ Inserted ${CONTRACTORS.length} contractors.`);
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('❌ Failed:', err.message);
    process.exit(1);
  } finally {
    client.release();
    await pool.end();
  }
}

seed();
